#!/usr/bin/env python3
"""Rows for `Decimal::exp_ctx` of `decimal_gda` at and around the coarse range guards (#796).

Writes `library/src/decimal_gda/exp_extreme_rows_wbtest.mbt`, a table of
`(rounding, precision, e_min, e_max, clamp, x, result, flags)`. The guards of the
coarse decision are `x >= 3 (e_max + 1)` (overflow) and `x <= -3 (1 - etiny)`
(underflow), `etiny = e_min - precision + 1`. The arguments are the guard, one
below it, one above it and ten times it, with both signs, in all eight rounding
modes of GDA 1.70 and in several contexts (decimal32, 64, 128 formats with clamp,
and two contexts without clamp).

No row comes from the library under test. `Context.exp` of libmpdec does not apply
the rounding direction when the result overflows or underflows (it gives Infinity
for round-down at exp(291) and zero for round-up at exp(-306), checked on
libmpdec 2.5.0, 4.0.0 and 4.0.1), so it is not the oracle for these rows. The true
value is computed with Python `decimal` at 400 digits (it is far from every
rounding boundary of the formats here) and rounded once into the context of the
row by `Context.plus`, whose overflow and underflow finalisation follows GDA 1.70
(Overflow, page 53; Underflow). Flags are written with the letters
x Inexact, r Rounded, o Overflow, u Underflow, s Subnormal, c Clamped, in that
order, `-` for none.

    python3 tools/generate_decimal_gda_exp_extreme_rows.py && moon fmt
    python3 tools/generate_decimal_gda_exp_extreme_rows.py --check
"""

from __future__ import annotations

import argparse
import decimal
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "library/src/decimal_gda/exp_extreme_rows_wbtest.mbt"

ROUNDINGS = {
    "half_even": decimal.ROUND_HALF_EVEN,
    "half_up": decimal.ROUND_HALF_UP,
    "half_down": decimal.ROUND_HALF_DOWN,
    "down": decimal.ROUND_DOWN,
    "ceiling": decimal.ROUND_CEILING,
    "floor": decimal.ROUND_FLOOR,
    "up": decimal.ROUND_UP,
    "05up": decimal.ROUND_05UP,
}
# (precision, e_min, e_max, clamp)
CONTEXTS = [
    (7, -95, 96, 1),
    (16, -383, 384, 1),
    (34, -6143, 6144, 1),
    (7, -95, 96, 0),
    (3, -9, 9, 0),
]
FLAG_LETTERS = [
    ("x", decimal.Inexact),
    ("r", decimal.Rounded),
    ("o", decimal.Overflow),
    ("u", decimal.Underflow),
    ("s", decimal.Subnormal),
    ("c", decimal.Clamped),
]


W = decimal.Context(prec=400, Emax=decimal.MAX_EMAX, Emin=decimal.MIN_EMIN, traps=[])


def context(rounding: str, p: int, e_min: int, e_max: int, clamp: int) -> decimal.Context:
    return decimal.Context(
        prec=p, rounding=ROUNDINGS[rounding], Emin=e_min, Emax=e_max,
        clamp=clamp, traps=[], flags=[],
    )


def arguments(p: int, e_min: int, e_max: int) -> list[int]:
    etiny = e_min - p + 1
    up = 3 * (e_max + 1)
    down = 3 * (1 - etiny)
    out: list[int] = []
    for guard in (up, down):
        for x in (guard - 1, guard, guard + 1, 10 * guard):
            out.append(x if guard == up else -x)
    return out


def flag_text(ctx: decimal.Context) -> str:
    letters = "".join(l for l, f in FLAG_LETTERS if ctx.flags[f])
    return letters or "-"


def build() -> list[tuple[str, int, int, int, int, str, str, str]]:
    rows = []
    for p, e_min, e_max, clamp in CONTEXTS:
        for rounding in ROUNDINGS:
            for x in arguments(p, e_min, e_max):
                ctx = context(rounding, p, e_min, e_max, clamp)
                # the argument is exact: it is an integer of at most p digits or is
                # rounded by the context first, as the library does for a `Decimal` of that precision
                result = ctx.plus(W.exp(decimal.Decimal(x)))
                rows.append((rounding, p, e_min, e_max, clamp, str(x), str(result), flag_text(ctx)))
    return rows


def render(rows: list[tuple[str, int, int, int, int, str, str, str]]) -> str:
    lines = [
        "///|",
        "// Generated by tools/generate_decimal_gda_exp_extreme_rows.py from Python `decimal`; do not edit.",
        "// Columns: rounding, precision, e_min, e_max, clamp, x, result, flags (x r o u s c, or -).",
        "",
        "///|",
        "let exp_extreme_rows : Array[(String, Int32, Int32, Int32, Int32, String, String, String)] = [",
    ]
    for row in rows:
        r, p, lo, hi, cl, x, res, fl = row
        lines.append(f'  ("{r}", {p}, {lo}, {hi}, {cl}, "{x}", "{res}", "{fl}"),')
    lines.append("]")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    rows = build()
    text_out = render(rows)
    if args.check:
        norm = lambda s: re.sub(r"\s+", "", s).replace(",)", ")").replace(",]", "]")
        if not OUTPUT.is_file() or norm(OUTPUT.read_text(encoding="utf-8")) != norm(text_out):
            print(f"{OUTPUT} is stale", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text_out, encoding="utf-8")
    print(f"{OUTPUT}: {len(rows)} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
