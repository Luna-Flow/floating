#!/usr/bin/env python3
"""Rows for the plain operators of `decimal_gda`: `+`, `-`, `*`, `/` and `sqrt`.

Writes `library/src/decimal_gda/plain_operator_rows_wbtest.mbt`, a table of
`(op, precision, a, b, expected)`. The plain operators are the free functions in
a private working context: precision P (the larger precision attribute of the
operands), half-even, extended rules, no clamp, no traps, largest adjusted
exponent 2,147,483,646, smallest exponent (Etiny) -2,147,483,645.

No row comes from the library under test and no model of its algorithm is used.
The expected value is computed with Python `decimal` (libmpdec, correctly
rounded for add, subtract, multiply, divide and sqrt) in the context
`Context(prec=P, rounding=ROUND_HALF_EVEN, Emax=2147483646,
Emin=-2147483645 + P - 1, clamp=0, traps=[])`. The operands are read with
`Context.create_decimal`, which rounds the text to P digits half-even as
`Decimal::from_string(text, precision=P)` does. A NaN result is written `nan` (the
executor checks `is_nan`; the sign and payload of a NaN are not compared), an
infinity `inf` or `-inf`.

    python3 tools/generate_decimal_gda_plain_rows.py && moon fmt
    python3 tools/generate_decimal_gda_plain_rows.py --check
"""

from __future__ import annotations

import argparse
import decimal
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "library/src/decimal_gda/plain_operator_rows_wbtest.mbt"

PRECISIONS = [3, 16, 34]
OPERANDS = [
    "0", "-0", "1", "-1", "-2.50", "1.5E+10", "123456789.123456789",
    "9999999999999999999999999999999999", "0.000123",
    "1E+2147483646", "9.99E+2147483646", "5E-2147483645",
    "Infinity", "NaN",
]
E_MAX = 2147483646
E_TINY = -2147483645


def context(p: int) -> decimal.Context:
    return decimal.Context(
        prec=p,
        rounding=decimal.ROUND_HALF_EVEN,
        Emax=E_MAX,
        Emin=E_TINY + p - 1,
        clamp=0,
        traps=[],
        flags=[],
    )


def text(value: decimal.Decimal) -> str:
    if value.is_nan():
        return "nan"
    if value.is_infinite():
        return "-inf" if value.is_signed() else "inf"
    return str(value)


def build() -> list[tuple[str, int, str, str, str]]:
    rows: list[tuple[str, int, str, str, str]] = []
    for p in PRECISIONS:
        ctx = context(p)
        operands = [(s, ctx.create_decimal(s)) for s in OPERANDS]
        for sa, a in operands:
            for sb, b in operands:
                rows.append(("add", p, sa, sb, text(ctx.add(a, b))))
                rows.append(("sub", p, sa, sb, text(ctx.subtract(a, b))))
                rows.append(("mul", p, sa, sb, text(ctx.multiply(a, b))))
                rows.append(("div", p, sa, sb, text(ctx.divide(a, b))))
            rows.append(("sqrt", p, sa, "-", text(ctx.sqrt(a))))
    return rows


def render(rows: list[tuple[str, int, str, str, str]]) -> str:
    lines = [
        "///|",
        "// Generated by tools/generate_decimal_gda_plain_rows.py from Python `decimal`; do not edit.",
        "// Columns: op, precision, a, b, expected (nan: only is_nan is checked).",
        "",
        "///|",
        "let plain_operator_rows : Array[(String, Int32, String, String, String)] = [",
    ]
    for op, p, a, b, expected in rows:
        lines.append(f'  ("{op}", {p}, "{a}", "{b}", "{expected}"),')
    lines.append("]")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text_out = render(build())
    if args.check:
        norm = lambda s: re.sub(r"\s+", "", s).replace(",)", ")").replace(",]", "]")
        if not OUTPUT.is_file() or norm(OUTPUT.read_text(encoding="utf-8")) != norm(text_out):
            print(f"{OUTPUT} is stale", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text_out, encoding="utf-8")
    print(f"{OUTPUT}: {text_out.count(chr(10)) - 7} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
