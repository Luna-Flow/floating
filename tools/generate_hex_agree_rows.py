#!/usr/bin/env python3
"""Rows for the hex reader in the unbounded exponent range (issue #256, IEEE 754-2019 5.12.3).

Writes `library/src/binary/hex_agree_rows_wbtest.mbt`: ten hexSequences, each rounded to nearest
(ties to even) at the precisions 1, 11, 24, 53, 64 and 113. The expected value is exact rational
arithmetic (`fractions`) and the grid rounding of `generate_hex_ctx_rows`; no reader of
the library is involved. These rows replace a test that compared `from_hex_ctx` with `from_hex`.

    python3 tools/generate_hex_agree_rows.py && moon fmt
    python3 tools/generate_hex_agree_rows.py --check
"""

from __future__ import annotations

import argparse
import re
import sys
from fractions import Fraction
from pathlib import Path

import generate_hex_ctx_rows as rounding

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "library/src/binary/hex_agree_rows_wbtest.mbt"
SOURCES = [
    "0x1.fffffffffffff8p0", "-0x1.00000000000008p0", "0x1.0000018p0", "0x.8p1",
    "0xABCDEF123456789p-40", "0x1p-1074", "-0x1.8p-1075", "0x1p1023", "0x0p0", "-0x0.0p5",
]
PRECISIONS = [1, 11, 24, 53, 64, 113]
HEX_RE = re.compile(r"^(-?)0[xX]([0-9a-fA-F]*)\.?([0-9a-fA-F]*)[pP]([+-]?\d+)$")


def parse_hex(text: str) -> tuple[bool, Fraction]:
    """(negative, exact value) of a hexSequence, by the grammar of 5.12.3."""
    match = HEX_RE.match(text)
    assert match is not None, text
    sign, whole, fraction, exponent = match.groups()
    digits = whole + fraction
    mantissa = int(digits, 16) if digits else 0
    exponent2 = int(exponent) - 4 * len(fraction)
    value = Fraction(mantissa) * Fraction(2) ** exponent2
    return sign == "-", value


def expected(text: str, precision: int) -> str:
    """The printed result (library form: odd mantissa, binary exponent) of rounding to nearest even."""
    negative, value = parse_hex(text)
    if value == 0:
        return "-0" if negative else "0"
    # the value is far inside the implementation range, so the grid is that of its own binade
    # (2^EMIN cannot be built as a rational)
    grid = rounding.binade(value) - precision + 1
    count = rounding.round_grid(value, grid, "RNE", negative)
    return rounding.render(negative, count, grid)


def rows() -> list[tuple[str, int, str]]:
    return [(text, p, expected(text, p)) for text in SOURCES for p in PRECISIONS]


def render_file(table: list[tuple[str, int, str]]) -> str:
    lines = [
        "// Generated by tools/generate_hex_agree_rows.py; do not edit.",
        "// Hex sequences rounded to nearest even in the unbounded exponent range, exact rational arithmetic:",
        "// (hexSequence, precision, expected).",
        "// oracle-file: A",
        "// producer: tools/generate_hex_agree_rows.py",
        "// input: ten hexSequences at precisions 1, 11, 24, 53, 64, 113, round to nearest even, unbounded exponent range",
        "// library-ran: no",
        "",
        "///|",
        "fn hex_agree_rows() -> Array[(String, Int32, String)] {",
        "  [",
    ]
    for text, p, value in table:
        lines.append(f'    ("{text}", {p}, "{value}"),')
    lines += ["  ]", "}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render_file(rows())
    if args.check:
        squeeze = lambda value: "".join(value.split()).replace(",)", ")").replace(",]", "]")
        ok = OUTPUT.is_file() and squeeze(OUTPUT.read_text(encoding="utf-8")) == squeeze(text)
        if not ok:
            print(f"stale: {OUTPUT}", file=sys.stderr)
        return 0 if ok else 1
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"{OUTPUT}: {len(rows())} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
