#!/usr/bin/env python3
"""Enclosures of exp, ln, sin, cos and acos (for pi) from GNU MPFR, for the tests of the series kernels.

Reads the requests `tools/enclosure_requests.txt` (one `op argument bits` per line, `argument`
a hexSequence written by `Binary::to_hex`, `bits` the precision of the enclosure) and writes
`library/src/binary/enclosure_rows_wbtest.mbt`: for each request the two MPFR results of `op`
at `bits` bits rounded toward negative and toward positive infinity (the exact function value
lies between them, they are at most one unit apart). A table row is

    (op, argument, bits, low, gap)

where `low` is the downward result and `gap` is the exponent k of the distance 2^k to the upward
result ("" when both are equal), so the pair is (low, low + 2^k).

The requests are inputs only: the library produced no expected value. A test that needs another
enclosure asks for it through `mpfr_enclosure`, which aborts with the missing request; add the
line to the requests file and run

    python3 tools/generate_enclosure_rows.py && moon fmt
    python3 tools/generate_enclosure_rows.py --check

Needs `cc`, GMP and MPFR, as `generate_function_boundary_rows.py` does.
"""

from __future__ import annotations

import argparse
import sys
from fractions import Fraction
from pathlib import Path

import generate_function_boundary_rows as boundary

ROOT = Path(__file__).resolve().parents[1]
REQUESTS = ROOT / "tools/enclosure_requests.txt"
OUTPUT = ROOT / "library/src/binary/enclosure_rows_wbtest.mbt"
OPERATIONS = ("exp", "ln", "sin", "cos", "acos")
Request = tuple[str, str, int]


def parse_requests(text: str) -> list[Request]:
    requests: list[Request] = []
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        op, argument, bits = line.split()
        if op not in OPERATIONS:
            raise ValueError(f"unknown operation {op}")
        requests.append((op, argument, int(bits)))
    return requests


def hex_value(text: str) -> Fraction:
    sign = -1 if text.startswith("-") else 1
    mantissa, exponent = text.lstrip("-").removeprefix("0x").split("p")
    return sign * Fraction(int(mantissa, 16)) * Fraction(2) ** int(exponent)


def gap_exponent(low: str, high: str) -> str:
    """The exponent k with high = low + 2^k, or "" when they are equal."""
    difference = hex_value(high) - hex_value(low)
    if difference == 0:
        return ""
    if difference < 0 or difference.numerator & (difference.numerator - 1) or (difference.denominator & (difference.denominator - 1)):
        raise ValueError(f"gap {difference} is not a power of two")
    return str(difference.numerator.bit_length() - difference.denominator.bit_length())


def input_lines(requests: list[Request]) -> list[str]:
    lines: list[str] = []
    for index, (op, argument, bits) in enumerate(requests):
        for mode in ("d", "u"):
            lines.append(f"enc.{index}{mode} {op} {mode} {bits} - - - {argument} - - 0 ? ?")
    return lines


def build(requests: list[Request]) -> list[tuple[str, str, int, str, str]]:
    evaluated = boundary.evaluate(input_lines(requests))
    if len(evaluated) != 2 * len(requests):
        raise RuntimeError(f"the evaluator returned {len(evaluated)} rows for {len(requests)} requests")
    rows = []
    for index, (op, argument, bits) in enumerate(requests):
        low, high = evaluated[2 * index], evaluated[2 * index + 1]
        assert low[1] == op and high[1] == op and low[5] == "RTN" and high[5] == "RTP", (low, high)
        rows.append((op, argument, bits, low[10], gap_exponent(low[10], high[10])))
    return rows


def render_file(rows: list[tuple[str, str, int, str, str]]) -> str:
    lines = [
        "// Generated by tools/generate_enclosure_rows.py; do not edit.",
        "// Enclosures of exp, ln, sin and cos at the requested precision, GNU MPFR 4.2.2, rounded toward negative and toward positive infinity:",
        "// (op, argument, bits, low, gap) with the pair (low, low + 2^gap), gap \"\" when both are equal.",
        "// oracle-file: A",
        "// producer: tools/generate_enclosure_rows.py",
        "// input: tools/enclosure_requests.txt (arguments the series kernel tests use; inputs only)",
        "// library-ran: no",
        "",
    ]
    tuple_type = "(String, String, Int32, String, String)"
    chunk = 400
    parts = [rows[start : start + chunk] for start in range(0, len(rows), chunk)]
    for index, part in enumerate(parts):
        lines += ["///|", f"fn enclosure_rows_part{index}() -> Array[{tuple_type}] {{", "  ["]
        lines += [f'    ("{op}", "{argument}", {bits}, "{low}", "{gap}"),' for op, argument, bits, low, gap in part]
        lines += ["  ]", "}", ""]
    lines += ["///|", f"fn enclosure_rows() -> Array[{tuple_type}] {{", "  let rows = []"]
    lines += [f"  rows.append(enclosure_rows_part{index}())" for index in range(len(parts))]
    lines += ["  rows", "}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    requests = parse_requests(REQUESTS.read_text(encoding="utf-8"))
    text = render_file(build(requests))
    if args.check:
        squeeze = lambda value: "".join(value.split()).replace(",)", ")").replace(",]", "]")
        ok = OUTPUT.is_file() and squeeze(OUTPUT.read_text(encoding="utf-8")) == squeeze(text)
        if not ok:
            print(f"stale: {OUTPUT}", file=sys.stderr)
        return 0 if ok else 1
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"{OUTPUT}: {len(requests)} rows, {len(text)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
